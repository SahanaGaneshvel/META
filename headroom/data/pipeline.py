"""Build every processed table and the data report.

    python -m headroom.data.pipeline
"""
from __future__ import annotations

import json
import time

from ..config import PROCESSED, SITE
from .building import building_profile
from .ev_profile import ev_profile
from .sessions import load_sessions
from .site import assemble_site
from .weather import compare_with_station


def run() -> dict:
    t0 = time.time()
    PROCESSED.mkdir(parents=True, exist_ok=True)
    report: dict[str, dict] = {}

    sessions, report["sessions"] = load_sessions(SITE)
    ev, report["ev_profile"] = ev_profile(sessions, SITE)
    building, report["building"] = building_profile(SITE)
    openmeteo, report["weather_sources"] = compare_with_station(building["temp_c"], SITE)
    site, report["site"] = assemble_site(building, ev, openmeteo, SITE)

    n_ports = len(report["sessions"]["ports"])
    assert report["ev_profile"]["max_cars_plugged"] <= n_ports, "more cars plugged in than ports"
    assert report["ev_profile"]["peak_uncontrolled_kw"] <= n_ports * SITE.port_kw_cap + 1e-6
    assert report["ev_profile"]["energy_balance_error"] < 0.005
    assert report["building"]["hourly_energy_max_error_kw"] < 1e-6

    sessions.to_parquet(PROCESSED / "sessions.parquet", index=False)
    ev.to_parquet(PROCESSED / "ev_15min.parquet")
    building.to_parquet(PROCESSED / "building_15min.parquet")
    site.to_parquet(PROCESSED / "site_15min.parquet")

    lines = ["# Data report", "", "Generated by `python -m headroom.data.pipeline`. Spec: docs/DATA_SPEC.md.", ""]
    for name, stats in report.items():
        lines += [f"## {name}", "", "```json", json.dumps(stats, indent=2, default=str), "```", ""]
    (PROCESSED / "REPORT.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    print(f"built in {time.time() - t0:.0f}s")
    return report


if __name__ == "__main__":
    run()
